#!/usr/bin/env python3
"""Emit kargs_table.h: one row per registration slot of each k_dnc_scan3* kernel.

usage: python3 -I gen_kargs_table.py RELA.txt STUBS.tsv OUT.h NOTES.txt [NOTES.txt ...]
  RELA.txt   objdump -R flash_serve   (RELATIVE rows: slot VMA -> stub VMA addend)
  STUBS.tsv  analysis/function-map-kernel-stubs.tsv (col 1 = stub Ghidra addr = VMA + 0x100000, col 2 = mangled name)
  NOTES.txt  llvm-readelf --notes of a code object (per-kernel .args offset/size, .kernarg_segment_size)
"""
import re
import sys
from pathlib import Path

GHIDRA_BIAS = 0x100000
PATTERN = re.compile(r'k_dnc_scan3')
MAXA = 32


def parse_rela(text):
    """slot VMA -> stub VMA for RELATIVE rows."""
    out = {}
    for m in re.finditer(r'^([0-9a-f]+)\s+R_X86_64_RELATIVE\s+\*ABS\*\+0x([0-9a-f]+)', text, re.MULTILINE):
        out[int(m.group(1), 16)] = int(m.group(2), 16)
    return out


def parse_stubs(text):
    """stub VMA -> mangled name."""
    out = {}
    for line in text.splitlines():
        f = line.split('\t')
        if len(f) >= 2 and re.fullmatch(r'[0-9a-f]+', f[0]):
            out[int(f[0], 16) - GHIDRA_BIAS] = f[1]
    return out


def parse_notes(text):
    """mangled name -> {size, args: [(offset, size)]} from the AMDGPU metadata YAML subset."""
    kernels, cur, arg = {}, None, None
    for line in text.splitlines():
        if re.match(r'^\s{2}- \.args:', line):
            cur = {'args': [], 'size': 0, 'name': None}
            arg = None
            continue
        if cur is None:
            continue
        m = re.match(r'^\s{6}(?:- |  )\.offset:\s+(\d+)', line)
        if m:
            arg = [int(m.group(1)), None]
            continue
        m = re.match(r'^\s{8}\.size:\s+(\d+)', line)
        if m and arg is not None and arg[1] is None:
            arg[1] = int(m.group(1))
            cur['args'].append(tuple(arg))
            continue
        m = re.match(r'^\s{4}\.kernarg_segment_size:\s+(\d+)', line)
        if m:
            cur['size'] = int(m.group(1))
            continue
        m = re.match(r'^\s{4}\.name:\s+(\S+)', line)
        if m:
            cur['name'] = m.group(1)
            kernels[cur['name']] = cur
            cur = None
    return kernels


def build_rows(rela, stubs, kernels):
    rows = []
    for slot in sorted(rela):
        stub = rela[slot]
        name = stubs.get(stub)
        if name is None or not PATTERN.search(name) or name not in kernels:
            continue
        k = kernels[name]
        tap = int((128, 40) in k['args'] and (168, 40) in k['args'])
        rows.append((slot, stub, name, k['size'], k['args'], tap))
    return rows


def emit(rows):
    o = ['/* generated by gen_kargs_table.py; do not edit */',
         f'#define KT_MAXA {MAXA}',
         'struct kentry { unsigned long slot_vma, stub_vma; const char *name; unsigned kernarg_size;',
         '  unsigned nargs, has_tap; unsigned short aoff[KT_MAXA], asz[KT_MAXA]; };',
         'static const struct kentry KTAB[] = {']
    for slot, stub, name, size, args, tap in rows:
        assert len(args) <= MAXA, name
        offs = ','.join(str(a[0]) for a in args)
        szs = ','.join(str(a[1]) for a in args)
        o.append(f'  {{0x{slot:x}UL, 0x{stub:x}UL, "{name}", {size}, {len(args)}, {tap}, {{{offs}}}, {{{szs}}}}},')
    o.append('};')
    o.append(f'#define KTAB_N {len(rows)}')
    return '\n'.join(o) + '\n'


def build_names(rela, stubs):
    """Sorted (slot VMA, mangled name) for every registration slot whose stub is in the stub map."""
    return [(slot, stubs[stub]) for slot, stub in sorted(rela.items()) if stub in stubs]


def emit_names(names):
    o = ['/* generated by gen_kargs_table.py; do not edit. Sorted by slot_vma. */',
         'static const struct { unsigned long slot_vma; const char *name; } KNAMES[] = {']
    o += [f'  {{0x{slot:x}UL, "{name}"}},' for slot, name in names]
    o += ['};', f'#define KNAMES_N {len(names)}']
    return '\n'.join(o) + '\n'


def main(argv):
    rela = parse_rela(Path(argv[1]).read_text())
    stubs = parse_stubs(Path(argv[2]).read_text())
    kernels = {}
    for p in argv[4:]:
        kernels.update(parse_notes(Path(p).read_text()))
    rows = build_rows(rela, stubs, kernels)
    Path(argv[3]).write_text(emit(rows))
    names = build_names(rela, stubs)
    Path(argv[3]).with_name('kernel_names.h').write_text(emit_names(names))
    print(f'{len(rows)} slots, {sum(r[5] for r in rows)} with Tap+NormFold; {len(names)} named handles', file=sys.stderr)


if __name__ == '__main__':
    main(sys.argv)
